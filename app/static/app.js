const $ = (selector) => document.querySelector(selector);
const screens = [...document.querySelectorAll('.screen')];
let activeMission = null;
let activeMissionId = null;
let activeProvider = 'Gemma via Ollama';
let nextRecommendation = null;

function escapeHtml(value = '') {
  return String(value).replace(/[&<>"']/g, (char) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
  })[char]);
}

function showScreen(id) {
  screens.forEach((screen) => { screen.hidden = screen.id !== id; });
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

function setBusy(button, busy, busyLabel, normalLabel) {
  button.disabled = busy;
  button.innerHTML = busy ? `${escapeHtml(busyLabel)} <span class="spinner" aria-hidden="true"></span>` : normalLabel;
}

function showMission(mission) {
  activeMission = mission;
  $('#drills-completed').max = mission.drills.length;
  const drills = mission.drills.map((drill, index) => `
    <li class="drill"><div class="drill-number">0${index + 1}</div><div><h3>${escapeHtml(drill.name)} <span>${drill.duration_minutes} min</span></h3><p>${escapeHtml(drill.instructions)}</p></div></li>
  `).join('');
  $('#mission-content').innerHTML = `
    <div class="mission-heading"><h1>${escapeHtml(mission.title)}</h1><div class="mission-meta"><span>${mission.duration_minutes} MINUTES</span><span>${escapeHtml(mission.goal.replaceAll('_', ' '))}</span></div></div>
    <div class="warmup"><strong>Warm up · ${mission.warmup_minutes} min</strong><p>${mission.warmup.map(escapeHtml).join(' ')}</p></div>
    <ol class="drill-list">${drills}</ol>
    <div class="challenge"><div class="eyebrow">YOUR CHALLENGE</div><p>${escapeHtml(mission.challenge.description)}</p><strong>${escapeHtml(mission.challenge.success_metric)}</strong></div>
    <div class="cooldown"><strong>Cool down · ${mission.cooldown_minutes} min</strong><p>${mission.cooldown.map(escapeHtml).join(' ')}</p></div>
    <p class="motivation">${escapeHtml(mission.motivation)}</p>
    <p class="safety-note">${escapeHtml(mission.safety_note)}</p>
    <button id="go-outside" class="button button-outside button-large full-width">GO OUTSIDE <span aria-hidden="true">↗</span></button>
    <div class="ai-note">Mission generated by ${escapeHtml(activeProvider)}.</div>
  `;
  $('#go-outside').addEventListener('click', () => showScreen('outside-screen'));
  showScreen('mission-screen');
}

$('#create-mission').addEventListener('click', () => showScreen('setup-screen'));
document.querySelectorAll('[data-screen]').forEach((button) => {
  button.addEventListener('click', () => showScreen(button.dataset.screen));
});

$('#setup-form').addEventListener('submit', async (event) => {
  event.preventDefault();
  const button = $('#generate-button');
  const error = $('#setup-error');
  error.textContent = '';
  const raw = Object.fromEntries(new FormData(event.currentTarget));
  raw.available_time = Number(raw.available_time);
  if (!raw.setting) raw.setting = null;
  setBusy(button, true, 'Asking Gemma…', 'Build my mission <span aria-hidden="true">↗</span>');
  try {
    const response = await fetch('/api/missions', {
      method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(raw)
    });
    const data = await response.json();
    if (!response.ok) throw new Error(data.detail || 'Could not build this mission.');
    activeMissionId = data.mission_id;
    activeProvider = data.ai_provider;
    showMission(data.mission);
  } catch (err) {
    error.textContent = err.message.includes('fetch')
      ? 'JobiGo could not reach its server. Try refreshing the page.'
      : err.message;
  } finally {
    setBusy(button, false, '', 'Build my mission <span aria-hidden="true">↗</span>');
  }
});

$('#return-button').addEventListener('click', () => showScreen('report-screen'));

$('#report-form').addEventListener('submit', async (event) => {
  event.preventDefault();
  if (!activeMission || !activeMissionId) return;
  const button = $('#review-button');
  const error = $('#report-error');
  error.textContent = '';
  const report = Object.fromEntries(new FormData(event.currentTarget));
  for (const key of ['attempts', 'successful_attempts', 'goals', 'completed_drills']) report[key] = Number(report[key]);
  setBusy(button, true, 'Gemma is reflecting…', 'Reflect with Gemma <span aria-hidden="true">↗</span>');
  try {
    const response = await fetch('/api/sessions', {
      method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ mission_id: activeMissionId, mission: activeMission, report })
    });
    const data = await response.json();
    if (!response.ok) throw new Error(data.detail || 'Could not review the session.');
    nextRecommendation = data.next_session;
    renderReview(data);
    await refreshProgress();
    showScreen('review-screen');
  } catch (err) {
    error.textContent = err.message.includes('fetch')
      ? 'JobiGo could not reach its server. Try again when you have a connection.'
      : err.message;
  } finally {
    setBusy(button, false, '', 'Reflect with Gemma <span aria-hidden="true">↗</span>');
  }
});

function renderReview(data) {
  const review = data.review;
  const next = data.next_session;
  $('#review-content').innerHTML = `
    <h1>Session complete.</h1>
    <p class="review-summary">${escapeHtml(review.performance_summary)}</p>
    <div class="reflection-line"><span>STRONGEST AREA</span><strong>${escapeHtml(review.strongest_area)}</strong></div>
    <div class="reflection-line"><span>ONE THING TO BUILD</span><strong>${escapeHtml(review.weakness)}</strong></div>
    <div class="recommendation"><div class="eyebrow">YOUR NEXT SESSION</div><h2>${escapeHtml(next.goal.replaceAll('_', ' '))} · ${next.available_time} min</h2><p>${escapeHtml(next.reason)}</p><small>${escapeHtml(next.level)} · ${escapeHtml(next.equipment.replaceAll('_', ' '))}</small></div>
    <p class="actionable">${escapeHtml(review.actionable_recommendation)}</p>
    <div class="ai-note">Session review and next step generated by Gemma via Ollama.</div>
  `;
}

$('#plan-next').addEventListener('click', () => {
  if (!nextRecommendation) return showScreen('setup-screen');
  const values = nextRecommendation;
  $(`#setup-form [name="available_time"][value="${values.available_time}"]`).checked = true;
  $('#level').value = values.level;
  $('#goal').value = values.goal;
  $('#equipment').value = values.equipment;
  $('#setting').value = values.setting || '';
  showScreen('setup-screen');
});

async function refreshProgress() {
  try {
    const response = await fetch('/api/sessions');
    if (!response.ok) return;
    const sessions = await response.json();
    const count = sessions.session_count;
    $('#progress-count').textContent = count ? `${count} session${count === 1 ? '' : 's'} played` : 'Ready for your first session';
  } catch { /* Progress is a small convenience, not required to play. */ }
}

refreshProgress();
